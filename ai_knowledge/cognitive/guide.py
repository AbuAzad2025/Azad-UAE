def resolve_guide_topic(tokens: frozenset[str]) -> str | None:
    for token in sorted(tokens, key=len, reverse=True):
        if token in GUIDE_TOPICS:
            return token
        if token.startswith("ال") and len(token) > 4 and token[2:] in GUIDE_TOPICS:
            return token[2:]
    return None


def guide_topics_list() -> str:
    return "، ".join(sorted({v["title"] for v in GUIDE_TOPICS.values()}))
